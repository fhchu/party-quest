#!/usr/bin/env bash
# Builds a trimmed Godot web export template (release, no threads) from
# source, with the options in custom.py, and copies it to the directory given
# (default: deploy/web-template/out, ignored by git). The engine source,
# Emscripten and SCons are fetched once into a cache outside the repo
# (PQ_CACHE, default ~/.cache/party-quest/web-template). The first build
# takes a long while; later ones reuse the cache. Needs uv
# (https://docs.astral.sh/uv/).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
out="${1:-$here/out}"
godot="${GODOT_BIN:-godot}"
cache="${PQ_CACHE:-$HOME/.cache/party-quest/web-template}"

# A template only works with the editor version that exports with it, so
# the version comes from the editor ("4.7.2.stable.<build>.<hash>").
version="$("$godot" --version | cut -d. -f1-3)"
# The Emscripten the official template for that version was built with: it
# prints "Build configuration: Emscripten <version>" in the browser console.
# Update it with each Godot upgrade.
emscripten=4.0.20
# SCons 4.4 is the oldest Godot's SConstruct accepts; pinned so a rebuild
# uses the same build tool.
scons_version=4.10.1
python_version=3.12

mkdir -p "$cache" "$out"
src="$cache/godot-$version-stable"
if [ ! -d "$src" ]; then
	curl -fsSL "https://github.com/godotengine/godot/archive/refs/tags/$version-stable.tar.gz" \
		| tar -xz -C "$cache"
fi

# emsdk needs Python 3.10 or newer, which macOS doesn't ship; uv fetches one
# into its own store.
venv="$cache/venv"
if [ ! -x "$venv/bin/scons" ]; then
	uv venv -q --python "$python_version" "$venv"
	uv pip install -q --python "$venv/bin/python" "scons==$scons_version"
fi
export EMSDK_PYTHON="$venv/bin/python"

emsdk="$cache/emsdk"
if [ ! -d "$emsdk" ]; then
	mkdir -p "$emsdk"
	curl -fsSL https://github.com/emscripten-core/emsdk/archive/refs/heads/main.tar.gz \
		| tar -xz -C "$emsdk" --strip-components 1
fi
"$emsdk/emsdk" install "$emscripten"
"$emsdk/emsdk" activate "$emscripten" >/dev/null
# emsdk_env.sh is generated by the install above.
# shellcheck disable=SC1091
EMSDK_QUIET=1 source "$emsdk/emsdk_env.sh"

jobs="$(sysctl -n hw.ncpu 2>/dev/null || nproc)"
(cd "$src" && "$venv/bin/scons" platform=web target=template_release threads=no \
	profile="$here/custom.py" -j"$jobs")
cp "$src/bin/godot.web.template_release.wasm32.nothreads.zip" "$out/"
echo "template: $out/godot.web.template_release.wasm32.nothreads.zip"
